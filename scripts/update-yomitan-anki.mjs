#!/usr/bin/env node
// Bundles Yomitan's Anki note building (AnkiNoteBuilder, the Handlebars template renderer with
// Yomitan's helpers, and the default field templates) with Hiroi's glue
// (scripts/yomitan-anki/hiroi-anki.js) into app/src/main/assets/yomitan/anki.js, which Hiroi runs
// in a WebView to fill Anki fields exactly as Yomitan does. The default templates are also copied
// to app/src/main/assets/yomitan/ for Hiroi's template editor, and its standard markers to markers.json.
//
// Usage: node scripts/update-yomitan-anki.mjs [yomitan-release-tag]
//    or: podman run --rm -v "$PWD":/work:Z -w /work docker.io/library/node:24-slim \
//          node scripts/update-yomitan-anki.mjs

import {execFileSync} from 'node:child_process';
import {copyFile, mkdir, mkdtemp, readFile, rm, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {tmpdir} from 'node:os';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const TAG = process.argv[2] ?? '26.11.2.0';
const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(REPO_ROOT, 'app/src/main/assets/yomitan');

async function download(url, file) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
    await writeFile(file, Buffer.from(await response.arrayBuffer()));
}

const dir = await mkdtemp(join(tmpdir(), 'yomitan-anki-'));
try {
    console.log(`==> Yomitan ${TAG}`);
    await download(`https://codeload.github.com/yomidevs/yomitan/tar.gz/refs/tags/${TAG}`, join(dir, 'yomitan.tar.gz'));
    execFileSync('tar', ['xzf', 'yomitan.tar.gz', '--strip-components=1'], {cwd: dir});

    // Only what the bundle needs, in the versions Yomitan uses. yomitan-handlebars is Yomitan's
    // Handlebars fork that renders without eval, on top of handlebars' parser; it's a git
    // dependency, so take its tarball.
    const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
    const deps = {...pkg.dependencies, ...pkg.devDependencies};
    const handlebarsCommit = deps['yomitan-handlebars'].split('#')[1];
    // In a folder of their own: in Yomitan's, npm would resolve all of Yomitan's dev dependencies.
    console.log('==> npm install esbuild, linkedom, handlebars, yomitan-handlebars');
    const modules = join(dir, 'hiroi-deps');
    await mkdir(modules);
    await writeFile(join(modules, 'package.json'), '{"private": true}\n');
    execFileSync('npm', [
        'install', '--no-save', '--ignore-scripts', '--no-audit', '--no-fund', '--no-package-lock',
        `esbuild@${deps.esbuild}`, `linkedom@${deps.linkedom}`, `handlebars@${deps.handlebars}`,
        `yomitan-handlebars@https://codeload.github.com/yomidevs/yomitan-handlebars/tar.gz/${handlebarsCommit}`,
    ], {cwd: modules, stdio: 'inherit'});

    await copyFile(join(REPO_ROOT, 'scripts/yomitan-anki/hiroi-anki.js'), join(dir, 'hiroi-anki.js'));
    const esbuild = createRequire(join(modules, 'package.json'))('esbuild');
    console.log('==> Bundling');
    await esbuild.build({
        entryPoints: [join(dir, 'hiroi-anki.js')],
        bundle: true,
        format: 'iife',
        target: 'chrome100',
        outfile: join(OUT, 'anki.js'),
        loader: {'.handlebars': 'text'},
        legalComments: 'none',
        minify: true,
        nodePaths: [join(modules, 'node_modules')],
        banner: {
            js: `// Generated by scripts/update-yomitan-anki.mjs from Yomitan ${TAG} (https://github.com/yomidevs/yomitan,\n` +
                '// GPL-3.0-or-later, Copyright (C) 2023-2026 Yomitan Authors, 2020-2022 Yomichan Authors), its libraries\n' +
                '// (yomitan-handlebars, MIT; linkedom, ISC) and scripts/yomitan-anki/hiroi-anki.js. Do not edit.',
        },
        plugins: [{
            // ext/lib/*.js are built by Yomitan's build-libs from dev/lib/*.js; use those directly.
            name: 'yomitan-lib',
            setup(build) {
                build.onResolve({filter: /\/lib\/(handlebars|linkedom)\.js$/}, (args) => ({
                    path: join(dir, 'dev/lib', args.path.split('/').pop()),
                }));
            },
        }],
    });
    await mkdir(OUT, {recursive: true});
    await copyFile(join(dir, 'ext/data/templates/default-anki-field-templates.handlebars'), join(OUT, 'default-anki-field-templates.handlebars'));
    // The standard markers, as Yomitan's card format editor offers them
    const {getStandardFieldMarkers} = await import(join(dir, 'ext/js/data/anki-template-util.js'));
    await writeFile(join(OUT, 'markers.json'), JSON.stringify(getStandardFieldMarkers('term', 'ja'), null, 1) + '\n');
    await writeFile(join(OUT, 'VERSION'), `${TAG}\n`);
    console.log(`==> ${OUT}/anki.js`);
} finally {
    await rm(dir, {recursive: true, force: true});
}
